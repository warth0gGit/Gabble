import AppKit
import ApplicationServices
import Carbon.HIToolbox

/// Types text into whichever app has focus by pasting it, then puts the
/// user's clipboard back. Pasting works in nearly every app, including Word,
/// browsers and Electron apps like Claude and Teams.
@MainActor
enum TextInserter {
    static func insert(_ text: String) {
        guard !text.isEmpty else { return }
        let pasteboard = NSPasteboard.general
        let saved = snapshot(of: pasteboard)

        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        // Ask clipboard managers to ignore this temporary entry.
        item.setString("", forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
        item.setString("", forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        pasteboard.writeObjects([item])
        let changeCount = pasteboard.changeCount

        sendPaste()

        // Give slower apps (Electron apps like Claude and Teams, or a busy Mac)
        // time to read the clipboard before the user's own copy is put back.
        DispatchQueue.main.asyncAfter(deadline: .now() + 1.0) {
            // Only restore if nothing else has used the clipboard since.
            guard pasteboard.changeCount == changeCount else { return }
            pasteboard.clearContents()
            if !saved.isEmpty { pasteboard.writeObjects(saved) }
        }
    }

    /// Types text straight into the focused app, without touching the clipboard.
    /// Used to show words live while you are still speaking.
    static func type(_ text: String) {
        guard !text.isEmpty else { return }
        let source = CGEventSource(stateID: .hidSystemState)
        let units = Array(text.utf16)
        var index = 0
        while index < units.count {
            let end = min(index + 16, units.count)
            var chunk = Array(units[index..<end])
            for keyDown in [true, false] {
                guard let event = CGEvent(keyboardEventSource: source, virtualKey: 0, keyDown: keyDown) else { continue }
                event.flags = []
                event.keyboardSetUnicodeString(stringLength: chunk.count, unicodeString: &chunk)
                event.post(tap: .cghidEventTap)
            }
            index = end
        }
    }

    /// Replaces text Warble just typed (immediately before the cursor) with a
    /// tidied version. It first checks the typed text is really there, so it
    /// never deletes anything you typed yourself. Returns false if skipped.
    @discardableResult
    static func replaceTyped(_ typed: String, with replacement: String) -> Bool {
        guard typed != replacement, !typed.isEmpty, !replacement.isEmpty else { return false }
        guard check(textBeforeCursorEndsWith: typed) == .matches else { return false }
        // Select the old words directly through Accessibility where the app
        // allows it: exact, and instant even for a long dictation.
        if selectBeforeCursor(typed) {
            insert(replacement)
            return true
        }
        let source = CGEventSource(stateID: .hidSystemState)
        let count = typed.count
        for _ in 0..<count {
            for keyDown in [true, false] {
                let event = CGEvent(keyboardEventSource: source, virtualKey: CGKeyCode(kVK_LeftArrow), keyDown: keyDown)
                event?.flags = .maskShift
                event?.post(tap: .cghidEventTap)
            }
        }
        insert(replacement)
        return true
    }

    enum FieldCheck { case matches, differs, unreadable }

    /// Selects `text`, which sits just before the cursor, via Accessibility, and
    /// checks the selection is exactly that text. Puts the cursor back and
    /// returns false if the app doesn't support it.
    private static func selectBeforeCursor(_ text: String) -> Bool {
        guard let element = focusedElement(),
              let range = selectedRange(of: element), range.length == 0 else { return false }
        let length = (text as NSString).length
        guard range.location >= length else { return false }
        var wanted = CFRange(location: range.location - length, length: length)
        guard let value = AXValueCreate(.cfRange, &wanted),
              AXUIElementSetAttributeValue(element, kAXSelectedTextRangeAttribute as CFString, value) == .success
        else { return false }
        var selected: CFTypeRef?
        if AXUIElementCopyAttributeValue(element, kAXSelectedTextAttribute as CFString, &selected) == .success,
           let selectedText = selected as? String, normalised(selectedText) == normalised(text) {
            return true
        }
        // Not what we expected: put the cursor back where it was.
        var original = range
        if let back = AXValueCreate(.cfRange, &original) {
            AXUIElementSetAttributeValue(element, kAXSelectedTextRangeAttribute as CFString, back)
        }
        return false
    }

    private static func focusedElement() -> AXUIElement? {
        let system = AXUIElementCreateSystemWide()
        var focused: CFTypeRef?
        guard AXUIElementCopyAttributeValue(system, kAXFocusedUIElementAttribute as CFString, &focused) == .success,
              let focused, CFGetTypeID(focused) == AXUIElementGetTypeID() else { return nil }
        return (focused as! AXUIElement)
    }

    private static func selectedRange(of element: AXUIElement) -> CFRange? {
        var rangeValue: CFTypeRef?
        guard AXUIElementCopyAttributeValue(element, kAXSelectedTextRangeAttribute as CFString, &rangeValue) == .success,
              let rangeValue, CFGetTypeID(rangeValue) == AXValueGetTypeID() else { return nil }
        var range = CFRange()
        guard AXValueGetValue(rangeValue as! AXValue, .cfRange, &range) else { return nil }
        return range
    }

    /// Apps built with Electron (Claude, Slack, Teams, VS Code) hide their text
    /// boxes from Accessibility until an assistive app asks for them. Asking
    /// lets Warble read what's in the box, so it can learn from your corrections.
    static func enableAccessibilityForFrontmostApp() {
        guard let app = NSWorkspace.shared.frontmostApplication,
              !accessibilityEnabledApps.contains(app.processIdentifier),
              let bundle = app.bundleURL else { return }
        accessibilityEnabledApps.insert(app.processIdentifier)
        let electron = bundle.appendingPathComponent("Contents/Frameworks/Electron Framework.framework")
        guard FileManager.default.fileExists(atPath: electron.path) else { return }
        let element = AXUIElementCreateApplication(app.processIdentifier)
        AXUIElementSetAttributeValue(element, "AXManualAccessibility" as CFString, kCFBooleanTrue)
    }

    private static var accessibilityEnabledApps: Set<pid_t> = []

    /// True when the focused text box is a normal Mac text field whose text
    /// Warble can read. Web-based boxes (the Claude app, Slack, browsers) don't
    /// reliably honour the key presses Warble uses to swap in tidied text, so
    /// there Warble shows live words in its capsule and types once at the end.
    static func focusedFieldSupportsLiveEditing() -> Bool {
        let system = AXUIElementCreateSystemWide()
        var focused: CFTypeRef?
        guard AXUIElementCopyAttributeValue(system, kAXFocusedUIElementAttribute as CFString, &focused) == .success,
              let focused, CFGetTypeID(focused) == AXUIElementGetTypeID() else { return false }
        let element = focused as! AXUIElement
        var value: CFTypeRef?
        var rangeValue: CFTypeRef?
        guard AXUIElementCopyAttributeValue(element, kAXValueAttribute as CFString, &value) == .success,
              value is String,
              AXUIElementCopyAttributeValue(element, kAXSelectedTextRangeAttribute as CFString, &rangeValue) == .success
        else { return false }
        // Inside a web page?
        var current: AXUIElement? = element
        for _ in 0..<25 {
            guard let node = current else { break }
            var role: CFTypeRef?
            if AXUIElementCopyAttributeValue(node, kAXRoleAttribute as CFString, &role) == .success,
               (role as? String) == "AXWebArea" {
                return false
            }
            var parent: CFTypeRef?
            guard AXUIElementCopyAttributeValue(node, kAXParentAttribute as CFString, &parent) == .success,
                  let parent, CFGetTypeID(parent) == AXUIElementGetTypeID() else { break }
            current = (parent as! AXUIElement)
        }
        return true
    }

    /// Checks, via Accessibility, whether the focused text field has `text` right before the cursor.
    static func check(textBeforeCursorEndsWith text: String) -> FieldCheck {
        let system = AXUIElementCreateSystemWide()
        var focused: CFTypeRef?
        guard AXUIElementCopyAttributeValue(system, kAXFocusedUIElementAttribute as CFString, &focused) == .success,
              let focused, CFGetTypeID(focused) == AXUIElementGetTypeID() else { return .unreadable }
        let element = focused as! AXUIElement
        var value: CFTypeRef?
        var rangeValue: CFTypeRef?
        guard AXUIElementCopyAttributeValue(element, kAXValueAttribute as CFString, &value) == .success,
              let full = value as? String,
              AXUIElementCopyAttributeValue(element, kAXSelectedTextRangeAttribute as CFString, &rangeValue) == .success,
              let rangeValue, CFGetTypeID(rangeValue) == AXValueGetTypeID() else { return .unreadable }
        var range = CFRange()
        guard AXValueGetValue(rangeValue as! AXValue, .cfRange, &range) else { return .unreadable }
        // Text is selected: the user has done something since; leave it alone.
        guard range.length == 0 else { return .differs }
        let ns = full as NSString
        guard range.location >= 0, range.location <= ns.length else { return .unreadable }
        // Some web views report an empty value even with text in the field.
        if ns.length == 0 { return .unreadable }
        let before = ns.substring(to: range.location)
        return normalised(before).hasSuffix(normalised(text)) ? .matches : .differs
    }

    static func textBeforeCursorEnds(with text: String) -> Bool {
        check(textBeforeCursorEndsWith: text) == .matches
    }

    /// Smooths over small changes apps make while you type (curly quotes, line endings).
    static func normalised(_ text: String) -> String {
        text.replacingOccurrences(of: "\r\n", with: "\n")
            .replacingOccurrences(of: "\r", with: "\n")
            .replacingOccurrences(of: "\u{2028}", with: "\n")
            .replacingOccurrences(of: "\u{2019}", with: "'")
            .replacingOccurrences(of: "\u{2018}", with: "'")
            .replacingOccurrences(of: "\u{201C}", with: "\"")
            .replacingOccurrences(of: "\u{201D}", with: "\"")
            .replacingOccurrences(of: "\u{00A0}", with: " ")
    }

    private static func sendPaste() {
        let source = CGEventSource(stateID: .combinedSessionState)
        let key = CGKeyCode(kVK_ANSI_V)
        let down = CGEvent(keyboardEventSource: source, virtualKey: key, keyDown: true)
        let up = CGEvent(keyboardEventSource: source, virtualKey: key, keyDown: false)
        down?.flags = .maskCommand
        up?.flags = .maskCommand
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)
    }

    private static func snapshot(of pasteboard: NSPasteboard) -> [NSPasteboardItem] {
        (pasteboard.pasteboardItems ?? []).map { original in
            let copy = NSPasteboardItem()
            for type in original.types {
                if let data = original.data(forType: type) {
                    copy.setData(data, forType: type)
                }
            }
            return copy
        }
    }

    /// The bundle identifier of the app the text will go into.
    static var frontmostBundleID: String? {
        NSWorkspace.shared.frontmostApplication?.bundleIdentifier
    }
}
